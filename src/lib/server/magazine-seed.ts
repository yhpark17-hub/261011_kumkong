const SEED_KEY = "seed:magazine:written-guide";

const GUIDE_BODY = `처음 금융공기업을 준비한다면 꼭 알아야 할 필기 유형과 용어를 정리했어요.

## NCS 직업기초능력이란?

NCS(국가직무능력표준)는 직무 수행에 필요한 능력을 국가가 표준화한 것으로, 대부분의 공공기관 필기시험에서 '직업기초능력' 평가에 활용됩니다. 기관마다 아래 10개 영역 중 일부를 골라 출제합니다.

- 의사소통능력 · 수리능력 · 문제해결능력
- 자기개발능력 · 자원관리능력 · 대인관계능력
- 정보능력 · 기술능력 · 조직이해능력 · 직업윤리

금융공기업은 이 중 **의사소통·수리·문제해결**을 기본으로 하고, 정보·자원관리·조직이해를 더하는 경우가 많습니다.

## NCS 출제 유형 3가지

### PSAT형
긴 지문과 표·그래프를 빠르게 해석하는 유형입니다. 자료해석·상황판단·언어논리 비중이 높아 시간 관리가 핵심이며, 금융공기업에서 자주 쓰입니다.

> [!팁] 준비 팁
> PSAT 기출(5급·민간경력자)로 실전 감각을 기르고, 문항당 풀이 시간을 정해 두세요.

### 모듈형
NCS 학습모듈의 이론·개념(의사소통 이론, 자원관리 기법, 조직 구조 등)을 묻는 유형입니다. 지문이 짧고 개념을 알면 빠르게 풀 수 있습니다.

> [!팁] 준비 팁
> NCS 직업기초능력 10개 영역 이론서를 한 번 정리해 두면 여러 기관에 활용됩니다.

### 피듈형
PSAT형과 모듈형을 섞은 유형입니다. 자료해석형 문제와 이론형 문제가 함께 나오며, 대행사에 따라 비중이 달라집니다.

> [!팁] 준비 팁
> 지원 기관의 최근 [필기 후기](/reviews)로 영역별 비중을 확인하고 약한 쪽을 집중 보완하세요.

## 전공 시험: 없음 · 통합 · 단일

| 구분 | 내용 | 특징 |
| --- | --- | --- |
| 전공 없음 | NCS·인적성 등 직업기초능력만 평가 | 비전공자도 도전하기 쉽지만 NCS 변별력이 커서 고득점 경쟁이 치열합니다. |
| 통합 전공 | 경영·경제·법 등 여러 과목을 한 시험에서 출제 | 경영·경제를 함께 공부해야 해 범위가 넓지만, 깊이는 단일전공보다 얕은 편입니다. |
| 단일 전공 | 직렬별로 전공 1과목을 선택해 응시 | 경영·경제·법·IT 등 한 과목을 깊게 묻습니다. 서술형·논술형이 많아 답안 작성 연습이 필요합니다. |

## A매치란?

주요 금융공기업들이 ==같은 날 같은 시간에 필기시험==을 치르는 것을 수험생들은 'A매치'라고 부릅니다. 하루에 한 곳만 응시할 수 있기 때문에, 서류 단계부터 어느 기관의 필기에 응시할지 전략적으로 정해야 합니다. [채용 캘린더](/)에서 필기 날짜가 겹치는 기관을 확인해 보세요.

## 블라인드 채용

2017년부터 공공기관은 입사지원서에 출신지역·가족관계·학력·신체조건·사진 등 직무와 무관한 정보를 요구하지 않는 블라인드 채용을 시행하고 있습니다. 반면 공공기관이 아닌 공제회·중앙회·시중은행은 기관마다 기준이 달라 학력이나 자격을 기재하기도 합니다.

## 알리오 경쟁률 보는 법

공공기관 경영정보 공개시스템 알리오(ALIO)에서 기관을 검색한 뒤 경영공시의 '신규채용 현황'을 보면 연도별 지원자 수와 채용 인원을 확인할 수 있습니다. 다만 일반·고졸·경력 채용이 합쳐진 수치인 경우가 많아, 대졸 신입 공채의 실제 경쟁률과는 차이가 있습니다.

> [!메모] 기관별 필기 구성
> 기관마다 NCS 유형, 전공 유무, 최근 경쟁률은 [기관 정보·경쟁률](/companies)에서 한눈에 비교할 수 있어요.
`;

export async function seedMagazine(c: Client): Promise<void> {
  const now = Date.now();
  // 먼저 표시를 남겨서, 여러 서버가 동시에 시작해도 한 번만 들어가게
  const claim = await c.execute({ sql: "INSERT OR IGNORE INTO kv (key, value, updated_at) VALUES (?, '1', ?)", args: [SEED_KEY, now] });
  if (!claim.rowsAffected) return;
  await c.execute({
    sql: `INSERT INTO articles (category, title, summary, body, tags, author, read_minutes, status, featured, published_at, created_at, updated_at)
          VALUES (?, ?, ?, ?, ?, ?, ?, 1, 1, ?, ?, ?)`,
    args: [
      "exam",
      "금융공기업 필기 가이드 — NCS 유형·전공·A매치 정리",
      "NCS 직업기초능력 10개 영역과 PSAT형·모듈형·피듈형의 차이\n전공 없음·통합·단일 전공 시험의 특징\nA매치, 블라인드 채용, 알리오 경쟁률 보는 법",
      GUIDE_BODY,
      "NCS,PSAT,A매치,블라인드 채용,알리오",
      "금콩 에디터",
      computeReadMinutes(GUIDE_BODY),
      now,
      now,
      now,
    ],
  });
}
